/* Phase 0: compute the hero keep-out boxes in viewport space and emit CSS vars.

   The hero film (src/assets/media/hero-1080.mp4, 1920x1080) renders with
   object-fit: cover inside a media box that overscans the viewport
   (top: -8%, height: 116%) and settles from scale 1.06 to 1. Copy must stay
   at least 32 px clear of the Kaaba (K1) and the Maqam Ibrahim (K2) at the
   worst case, which is the 1.06 settle frame.

   Film boxes were measured on every half-second frame of the encoded loop
   (docs/rebrand: kiswa spans x .50-.87, y roof .24 to base .88):
     K1 Kaaba        x .49-.89  y .23-.90
     K2 Maqam        x .30-.52  y .64-.90

   For each aspect band the script picks the object-position x that keeps all
   of K1 plus 32 px inside the viewport at rest (scale 1; during the 2 s settle
   the zoom may briefly crop it), while leaving the widest copy column. Text
   clearance uses the worse of the settle and rest frames. Where the column
   would be narrower than MIN_COLUMN, the hero switches to the plate layout
   below a computed width. Writes src/styles/hero-safe.css. Run: node scripts/hero-safe-zones.js
*/
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const FILM = { w: 1920, h: 1080 }
const K1 = { x1: 0.49, x2: 0.89, y1: 0.23, y2: 0.90 }
const K2 = { x1: 0.30, x2: 0.52, y1: 0.64, y2: 0.90 }
const OVERSCAN = { top: -0.08, height: 1.16 }
const SETTLE = 1.06
const CLEAR = 32
const MIN_COLUMN = 400   // was 520; the headline scales to the column (home.css), owner prefers the film at 100% zoom

// Representative viewports per aspect band (all at or above the 1024 px desktop breakpoint).
const BANDS = [
  { name: 'wide',   query: '(min-aspect-ratio: 16/9)',                              vps: [[1920, 1080], [1536, 864], [1280, 720], [2560, 1080]] },
  { name: '16x10',  query: '(min-aspect-ratio: 3/2) and (max-aspect-ratio: 16/9)',  vps: [[1440, 900], [1280, 800], [1366, 768], [1680, 1050]] },
  { name: '4x3',    query: '(max-aspect-ratio: 3/2)',                               vps: [[1024, 768], [1280, 1024], [1200, 900]] },
]

const margin = W => Math.min(80, Math.max(24, W * 0.055)) // clamp(24px, 5.5vw, 80px)

function map(W, H, px, scale) {
  const boxTop = OVERSCAN.top * H
  const boxH = OVERSCAN.height * H
  const s = Math.max(W / FILM.w, boxH / FILM.h)
  const fw = FILM.w * s
  const fh = FILM.h * s
  const ox = (W - fw) * px
  const oy = boxTop + (boxH - fh) * 0.5
  const cx = W / 2
  const cy = boxTop + boxH / 2
  const tx = x => cx + (ox + x * fw - cx) * scale
  const ty = y => cy + (oy + y * fh - cy) * scale
  const box = k => ({ x1: tx(k.x1), x2: tx(k.x2), y1: ty(k.y1), y2: ty(k.y2) })
  return { k1: box(K1), k2: box(K2) }
}

function solve(W, H) {
  // Smallest px (film anchored left) whose K1 right edge + 32 px stays in frame at the settle scale.
  let best = null
  for (let i = 0; i <= 100; i++) {
    const px = i / 100
    const m = map(W, H, px, 1)
    if (m.k1.x2 + CLEAR <= W && m.k1.x1 >= 0) { best = { px, ...m }; break }
  }
  if (!best) best = { px: 1, ...map(W, H, 1, 1), k1Clipped: true }
  const rest = map(W, H, best.px, 1)
  // Worst case for the copy column is whichever scale puts each box closest to the copy.
  const k1Left = Math.min(best.k1.x1, rest.k1.x1)
  const k2Top = Math.min(best.k2.y1, rest.k2.y1)
  const k2Left = Math.min(best.k2.x1, rest.k2.x1)
  const colStart = margin(W) + 24 // margin rule + inset
  const colEnd = k1Left - CLEAR
  return {
    W, H, px: best.px, k1Clipped: !!best.k1Clipped,
    k1Left, k1Top: Math.min(best.k1.y1, rest.k1.y1), k1Right: Math.max(best.k1.x2, rest.k1.x2),
    k2Left, k2Top, colStart, colEnd, colWidth: colEnd - colStart,
    columnBottomMax: k2Top - CLEAR,
  }
}

const pct = (v, of) => `${((v / of) * 100).toFixed(2)}%`
const rows = []
const log = []
let css = `/* GENERATED by scripts/hero-safe-zones.js. Do not edit by hand.
   Viewport-space keep-out boxes for the Home hero film at the worst case
   (settle scale ${SETTLE}, overscan ${Math.round(OVERSCAN.height * 100)}%). Copy, rules, the
   HUD and the pause toggle stay at least ${CLEAR}px clear of --k1-* and --k2-*.
   --hero-plate: 1 means the copy column is under ${MIN_COLUMN}px at this aspect,
   so the hero uses the 16:9 plate layout instead of copy over film. */\n`

for (const band of BANDS) {
  const results = band.vps.map(([W, H]) => solve(W, H))
  // One object-position per band: the most conservative (largest) px that any viewport needed.
  const px = Math.max(...results.map(r => r.px))
  const fixed = band.vps.map(([W, H]) => {
    const settle = map(W, H, px, SETTLE)
    const rest = map(W, H, px, 1)
    const k1Left = Math.min(settle.k1.x1, rest.k1.x1)
    const k2Top = Math.min(settle.k2.y1, rest.k2.y1)
    const k2Left = Math.min(settle.k2.x1, rest.k2.x1)
    const colStart = margin(W) + 24
    const colEnd = k1Left - CLEAR
    return { W, H, k1Left, k1Right: Math.max(settle.k1.x2, rest.k1.x2), k1Top: Math.min(settle.k1.y1, rest.k1.y1), k2Left, k2Top, colStart, colEnd, colWidth: colEnd - colStart }
  })
  const ref = fixed[0]
  // Column width grows with viewport width at a fixed aspect; find the first width where it reaches MIN_COLUMN.
  const aspect = ref.W / ref.H
  let plateBelow = 0
  for (let W = 1024; W <= 3840; W += 8) {
    const H = W / aspect
    const st = map(W, H, px, SETTLE), rs = map(W, H, px, 1)
    const col = Math.min(st.k1.x1, rs.k1.x1) - CLEAR - (margin(W) + 24)
    if (col >= MIN_COLUMN) { plateBelow = W; break }
  }
  const plate = plateBelow === 1024 ? 0 : 1
  css += `\n@media (min-width: 1024px) and ${band.query} {\n  .hero {\n` +
    `    --hero-obj-x: ${(px * 100).toFixed(0)}%;\n` +
    `    --k1-left: ${pct(ref.k1Left, ref.W)};\n    --k1-top: ${pct(ref.k1Top, ref.H)};\n` +
    `    --k2-left: ${pct(ref.k2Left, ref.W)};\n    --k2-top: ${pct(ref.k2Top, ref.H)};\n` +
    `    --col-end: calc(var(--k1-left) - ${CLEAR}px);\n` +
    `    --col-bottom-max: calc(var(--k2-top) - ${CLEAR}px);\n` +
    `    --hero-plate: 0;\n  }\n}\n` +
    (plate
      ? `@media (min-width: 1024px) and (max-width: ${(plateBelow || 3848) - 1}px) and ${band.query} {\n  .hero { --hero-plate: 1; }\n}\n`
      : '')
  log.push(`${band.name}: object-position ${(px * 100).toFixed(0)}%, copy over film from ${plateBelow ? plateBelow + 'px' : 'never'} wide`)
  for (const f of fixed) rows.push({ band: band.name, vp: `${f.W}x${f.H}`, objX: `${(px * 100).toFixed(0)}%`, k1Left: pct(f.k1Left, f.W), k1Right: pct(f.k1Right, f.W), k2Top: pct(f.k2Top, f.H), column: `${Math.round(f.colWidth)}px`, plate: f.colWidth < MIN_COLUMN ? 'plate' : 'over film' })
}

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'src', 'styles', 'hero-safe.css')
writeFileSync(out, css)
console.table(rows)
console.log(log.join('\n'))
console.log('wrote', path.relative(process.cwd(), out))
