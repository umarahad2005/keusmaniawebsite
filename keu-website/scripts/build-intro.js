/* Builds the inline preloader ("handshake") markup inside index.html from the
   traced KU mark (src/assets/brand/ku-mark-reversed.svg). Run after changing the
   mark:  node scripts/build-intro.js

   The intro must paint before React loads, so it is plain HTML + CSS keyframes:
   the orbit ring and swoosh are revealed through stroked masks whose
   stroke-dashoffset animates (the "self-draw"), the K, dome, Kaaba and U wipe in
   left to right through clip rects, and the aircraft lands last.
   src/components/motion/Preloader.jsx then adopts this node, opens the bands and
   glides the mark into the nav. Spec: docs/rebrand/DESIGN-LANGUAGE.md §3.3. */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const svgPath = path.join(root, 'src/assets/brand/ku-mark-reversed.svg')
const htmlPath = path.join(root, 'index.html')

// Orbit ring geometry measured from the traced artwork (render + bbox).
const RING = { cx: 497.5, cy: 527.5, r: 442.5 }
const SWOOSH = 'M323.6 534.3C58.9 841.8 782.8 526.8 810 407.9'
const WIPES = ['k', 'dome', 'kaaba', 'kaaba-band', 'u', 'crescent']

let svg = readFileSync(svgPath, 'utf8')
  .replace(/<\?xml[^>]*>/, '')
  .replace(/<title>[^<]*<\/title>/, '')
  .replace(/\s+/g, ' ')
  .replace(/id="([A-Za-z-]+)"/g, 'id="ki-$1"')
  .replace(/url\(#kuGold\)/g, 'url(#ki-kuGold)')

const ringD = `M${RING.cx - RING.r} ${RING.cy}A${RING.r} ${RING.r} 0 1 1 ${RING.cx + RING.r} ${RING.cy}A${RING.r} ${RING.r} 0 1 1 ${RING.cx - RING.r} ${RING.cy}`
const defs =
  `<mask id="ki-m-ring" maskUnits="userSpaceOnUse" x="0" y="0" width="1000" height="1000"><path class="ki-draw ki-draw--ring" d="${ringD}" pathLength="1" fill="none" stroke="#fff" stroke-width="160"/></mask>` +
  `<mask id="ki-m-sw" maskUnits="userSpaceOnUse" x="0" y="0" width="1000" height="1000"><path class="ki-draw ki-draw--sw" d="${SWOOSH}" pathLength="1" fill="none" stroke="#fff" stroke-width="150" stroke-linecap="round"/></mask>` +
  WIPES.map((id, i) => `<clipPath id="ki-c-${id}" clipPathUnits="userSpaceOnUse"><rect class="ki-wipe" style="animation-delay:${500 + i * 60}ms" x="0" y="0" width="1000" height="1000"/></clipPath>`).join('')

svg = svg.replace('<defs>', `<defs>${defs}`)
svg = svg.replace('<svg ', '<svg class="ki-mark" aria-hidden="true" focusable="false" ')
svg = svg.replace(/<g id="ki-(ring-gold|ring-green)"/g, '<g mask="url(#ki-m-ring)" id="ki-$1"')
svg = svg.replace('<g id="ki-swoosh"', '<g mask="url(#ki-m-sw)" id="ki-swoosh"')
for (const id of WIPES) svg = svg.replace(`<g id="ki-${id}"`, `<g clip-path="url(#ki-c-${id})" id="ki-${id}"`)
svg = svg.replace('<g id="ki-plane"', '<g class="ki-plane" id="ki-plane"')

const block = `<!-- keu-intro:start (generated by scripts/build-intro.js) -->
  <div class="keu-intro" id="keu-intro">
    <div class="ki-band ki-band--top"></div>
    <div class="ki-band ki-band--bottom"></div>
    <div class="ki-center" aria-hidden="true">
      <div class="ki-markwrap" id="ki-markwrap">${svg}</div>
      <div class="ki-rules"><i></i><i></i></div>
      <div class="ki-count" id="ki-count">00</div>
    </div>
    <div class="ki-hud">
      <a class="ki-hud__link" href="https://wa.me/923334883578" target="_blank" rel="noopener">WhatsApp +92 333 4883578</a>
      <button class="ki-hud__link" type="button" id="ki-skip">Skip intro</button>
    </div>
  </div>
  <!-- keu-intro:end -->`

const html = readFileSync(htmlPath, 'utf8')
const re = /<!-- keu-intro:start[\s\S]*?<!-- keu-intro:end -->/
if (!re.test(html)) throw new Error('index.html has no keu-intro markers')
writeFileSync(htmlPath, html.replace(re, block))
console.log('keu-intro written:', block.length, 'bytes')
